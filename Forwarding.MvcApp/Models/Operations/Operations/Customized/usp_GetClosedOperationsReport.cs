        private bool IsReportRunning()
        {
            string query = @"
                       SELECT 1
        FROM sys.dm_exec_connections AS qs
        CROSS APPLY sys.dm_exec_sql_text(qs.most_recent_sql_handle) st
        WHERE object_name(st.objectid) IN (
            'usp_GetClosedOperationsReport',
            'usp_GetClosedOperationsReportCLOSED',
            'OperationReportForwarding',
			'MES_CashReceiveReport' ,
			'MES_PaymentOrderReport',
			'VendorReport',
			'IsDirectReport',
			'CustodyReport'
                )";

            using (var conn = new SqlConnection(GetConnectionString()))
            using (var cmd = new SqlCommand(query, conn))
            {
                conn.Open();
                var result = cmd.ExecuteScalar();
                return false;
            }
        }

