        private async Task<MemoryStream> ExportReportToExcel(string storedProcedure, string reportName)
        {
            return await Task.Run(async () =>
            {
                var stopwatch = Stopwatch.StartNew();
                var stream = new MemoryStream();

                using (var conn = new SqlConnection(GetConnectionString()))
                using (var cmd = new SqlCommand(storedProcedure, conn))
                {
                    cmd.CommandType = CommandType.StoredProcedure;
                    cmd.CommandTimeout = 3600;
                    await conn.OpenAsync();

                    using (var reader = await cmd.ExecuteReaderAsync())
                    {
                        stopwatch.Stop();
                        Debug.WriteLine($"{reportName} - SQL Load Time: {stopwatch.Elapsed}");
                        stopwatch.Restart();

                        ExcelPackage.LicenseContext = LicenseContext.NonCommercial;
                        using (var package = new ExcelPackage())
                        {
                            var worksheet = package.Workbook.Worksheets.Add("Sheet1");

                            worksheet.Cells["A1"].LoadFromDataReader(reader, true);
                            worksheet.Cells[worksheet.Dimension.Address].AutoFitColumns();

                            package.SaveAs(stream); 
                        }
                    }
                }

                stopwatch.Stop();
                Debug.WriteLine($"{reportName} - Excel Generation Time: {stopwatch.Elapsed}");

                stream.Position = 0; 
                return stream;
            });
        }

        private FileStreamResult GetExcelFileStream(MemoryStream stream, string filePrefix)
        {
            string timestamp = DateTime.Now.ToString("yyyyMMdd_HHmmss");
            string fileName = $"{filePrefix}_{timestamp}.xlsx";
            return File(stream,
                        "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
                        fileName);
        }
